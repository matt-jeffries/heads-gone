// Builds a player list for every club in clubs.js from Wikidata and writes club-packs.js.
// Runs in GitHub Actions (.github/workflows/club-packs.yml); needs access to wikipedia.org and wikidata.org.
// Fame is approximated by Wikipedia sitelink count, so lists favour players known beyond the club.
import { readFile, writeFile } from "node:fs/promises";

const UA = "HeadsGone/0.2 (football party game; club pack builder; github.com/matt-jeffries/heads-gone)";
const root = new URL("../", import.meta.url);
const titles = JSON.parse(await readFile(new URL("scripts/club-wiki.json", root), "utf8"));
const window = {};
new Function("window", await readFile(new URL("clubs.js", root), "utf8"))(window);
const SKIP = new Set(process.env.SKIP?.split(",") || []);
const wait = (ms) => new Promise((r) => setTimeout(r, ms));

async function qid(title) {
  const u = `https://en.wikipedia.org/w/api.php?action=query&format=json&redirects=1&prop=pageprops&titles=${encodeURIComponent(title)}`;
  const j = await (await fetch(u, { headers: { "User-Agent": UA } })).json();
  const page = Object.values(j.query.pages)[0];
  return page?.pageprops?.wikibase_item || null;
}

async function players(q) {
  const sparql = `
SELECT ?p ?pLabel (MAX(?links) AS ?fame) WHERE {
  ?p p:P54/ps:P54 wd:${q} ;
     wdt:P106 wd:Q937857 ;
     wikibase:sitelinks ?links .
  FILTER(?links >= 3)
  SERVICE wikibase:label { bd:serviceParam wikibase:language "en". }
}
GROUP BY ?p ?pLabel
ORDER BY DESC(?fame)
LIMIT 50`;
  for (let attempt = 0; attempt < 3; attempt++) {
    const res = await fetch(`https://query.wikidata.org/sparql?format=json&query=${encodeURIComponent(sparql)}`,
      { headers: { "User-Agent": UA, Accept: "application/sparql-results+json" } });
    if (res.ok) {
      const j = await res.json();
      return [...new Set(j.results.bindings.map((b) => b.pLabel.value).filter((n) => !/^Q\d+$/.test(n)))];
    }
    await wait(5000 * (attempt + 1));
  }
  throw new Error("Wikidata query failed");
}

const out = [], log = [];
for (const club of window.CLUBS) {
  if (SKIP.has(club.id)) continue;
  try {
    const q = await qid(titles[club.id]);
    if (!q) { log.push(`${club.id}: no Wikidata item for "${titles[club.id]}"`); continue; }
    const list = await players(q);
    log.push(`${club.id}: ${q} ${list.length} players`);
    if (list.length >= 20) out.push({ id: club.id, players: list });
  } catch (e) { log.push(`${club.id}: ${e.message}`); }
  await wait(1200);
}
await writeFile(new URL("club-packs.js", root),
  `// Generated by scripts/fetch-club-packs.mjs on ${new Date().toISOString().slice(0, 10)}. Do not edit by hand.\n` +
  `window.CLUB_PACK_PLAYERS = ${JSON.stringify(Object.fromEntries(out.map((c) => [c.id, c.players])))};\n`);
await writeFile(new URL("scripts/club-packs-log.txt", root), log.join("\n") + "\n");
console.log(log.join("\n"));
console.log(`Wrote ${out.length} club packs`);
