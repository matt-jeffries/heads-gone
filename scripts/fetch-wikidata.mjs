// Builds extra categories from Wikidata and writes them to wikidata-categories.js.
// Usage: node scripts/fetch-wikidata.mjs   (Node 18+, needs access to query.wikidata.org)
//
// Fame is approximated by Wikipedia sitelink count: a player with articles in
// many languages is someone a pub crowd is likely to know.
import { writeFile } from "node:fs/promises";

const ENDPOINT = "https://query.wikidata.org/sparql";
const UA = "HeadsGone/0.1 (football party game; category builder)";

// Teams are named by their English Wikipedia article so we don't hardcode QIDs.
const CATEGORIES = [
  { id: "wd-chelsea", name: "Chelsea Legends", team: "Chelsea F.C." },
  { id: "wd-spurs", name: "Spurs Legends", team: "Tottenham Hotspur F.C." },
  { id: "wd-newcastle", name: "Newcastle Legends", team: "Newcastle United F.C." },
  { id: "wd-everton", name: "Everton Legends", team: "Everton F.C." },
  { id: "wd-mancity", name: "Man City Legends", team: "Manchester City F.C." },
  { id: "wd-leeds", name: "Leeds Legends", team: "Leeds United F.C." },
  { id: "wd-celtic", name: "Celtic Legends", team: "Celtic F.C." },
  { id: "wd-rangers", name: "Rangers Legends", team: "Rangers F.C." },
  { id: "wd-realmadrid", name: "Real Madrid Galácticos", team: "Real Madrid CF" },
  { id: "wd-barca", name: "Barcelona Stars", team: "FC Barcelona" },
  { id: "wd-brazil", name: "Brazil Internationals", team: "Brazil national football team" },
  { id: "wd-france", name: "France Internationals", team: "France national football team" },
  { id: "wd-scotland", name: "Scotland Internationals", team: "Scotland national football team", minLinks: 15 },
  { id: "wd-wales", name: "Wales Internationals", team: "Wales national football team", minLinks: 15 },
  // Decade filters use the start/end qualifiers on "member of sports team".
  { id: "wd-utd-80s", name: "Man United in the 80s", team: "Manchester United F.C.", from: 1980, to: 1989, minLinks: 10 },
  { id: "wd-pool-00s", name: "Liverpool in the 2000s", team: "Liverpool F.C.", from: 2000, to: 2009, minLinks: 15 },
];

function query({ team, from, to, minLinks = 25, limit = 60 }) {
  const decade = from
    ? `?st pq:P580 ?start . FILTER(YEAR(?start) <= ${to})
       OPTIONAL { ?st pq:P582 ?end } FILTER(!BOUND(?end) || YEAR(?end) >= ${from})`
    : "";
  return `
SELECT ?p ?pLabel (MAX(?links) AS ?fame) WHERE {
  ?article schema:about ?team ;
           schema:isPartOf <https://en.wikipedia.org/> ;
           schema:name "${team}"@en .
  ?p p:P54 ?st . ?st ps:P54 ?team .
  ${decade}
  ?p wdt:P106 wd:Q937857 ;            # occupation: association football player
     wikibase:sitelinks ?links .
  FILTER(?links >= ${minLinks})
  SERVICE wikibase:label { bd:serviceParam wikibase:language "en". }
}
GROUP BY ?p ?pLabel
ORDER BY DESC(?fame)
LIMIT ${limit}`;
}

async function run(sparql) {
  const url = `${ENDPOINT}?format=json&query=${encodeURIComponent(sparql)}`;
  const res = await fetch(url, { headers: { "User-Agent": UA, Accept: "application/sparql-results+json" } });
  if (!res.ok) throw new Error(`Wikidata answered ${res.status}`);
  const json = await res.json();
  return json.results.bindings
    .map((b) => b.pLabel.value)
    .filter((name) => !/^Q\d+$/.test(name)); // drop players with no English label
}

const out = [];
for (const cat of CATEGORIES) {
  try {
    const players = [...new Set(await run(query(cat)))];
    console.log(`${cat.name}: ${players.length} players`);
    if (players.length >= 15) {
      out.push({ id: cat.id, name: cat.name, blurb: "Built from Wikidata", players });
    }
  } catch (err) {
    console.error(`${cat.name}: ${err.message}`);
  }
  await new Promise((r) => setTimeout(r, 1000)); // be polite to the public endpoint
}

await writeFile(
  new URL("../wikidata-categories.js", import.meta.url),
  `// Generated by scripts/fetch-wikidata.mjs on ${new Date().toISOString().slice(0, 10)}. Do not edit by hand.\n` +
    `window.WIKIDATA_CATEGORIES = ${JSON.stringify(out, null, 2)};\n`
);
console.log(`Wrote ${out.length} categories to wikidata-categories.js`);
